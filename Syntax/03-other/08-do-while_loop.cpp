// in do while code runs first and condition is checked later and is used in menu driven programs, input validation, 

#include <iostream>
using namespace std;

int main() {
    int i = 10; //try with value 0
    do {
    cout << i << "\n";
    i++;
    }
    while (i < 5); //5th iteration will happen


    return 0;
}                                                        