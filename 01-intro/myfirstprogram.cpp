#include <iostream>
// is a header file library that lets us work with input and output objects, 
// such as cout (used in line 5). Header files add functionality to C++ programs.
using namespace std;
// means that we can use names for objects and variables from the standard library.
int main () {
// This is called a function. Any code inside its curly brackets {} will be executed.
    cout << "Hello World";
// cout (pronounced "see-out") is an object used together with the insertion operator (<<) to output/print text.
// Note: C++ is case-sensitive: "cout" and "Cout" has different meaning.    
    return 0;
// ends the main function.
}